"use strict";
// VM fixtures only: no application startup, persistent storage, native calls or network.
const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const sandbox = { window: { ZETER_CORE_UTILS: { escapeHtml: value => String(value).replace(/[&<>"']/g, char => `&#${char.charCodeAt(0)};`) } } };
sandbox.URLSearchParams = URLSearchParams;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname, "../app/js/core/runtime-capabilities-utils.js"), "utf8"), sandbox);
const owner = sandbox.window.ZETER_RUNTIME_CAPABILITIES_UTILS;
const browser = { location: { search: "" }, navigator: {}, isSecureContext: true };
const snapshot = (env = browser, info = null) => owner.getCapabilities({ windowRef: env, runtimeInfo: info });
const feature = (env, id, info = null) => snapshot(env, info).features.find(item => item.id === id);
assert.equal(snapshot().kind, "browser");
assert.equal(feature(browser, "windowsStickers").status, "unavailable");
assert.equal(feature(browser, "workspace").status, "available");
const markerOnly = { ...browser, location: { search: "?native=1" } };
assert.equal(snapshot(markerOnly).pending, true, "a native URL marker must not grant system capabilities");
assert.equal(feature(markerOnly, "windowsStickers").status, "pending");
const mobile = { ...browser, navigator: { userAgent: "Android", standalone: true } };
assert.equal(snapshot(mobile).kind, "pwa");
assert.equal(feature(mobile, "windowsStickers").status, "unavailable", "installing PWA cannot grant native rights");
let calls = 0;
const api = new Proxy({ load_state() {}, open_sticky_window() {}, get_windows_startup_status() {}, set_windows_startup_enabled() {}, read_managed_document() {}, save_managed_document() {}, show_system_notification() {}, get_app_update_status() {}, prepare_app_update() {}, install_app_update() {} }, { get(target, name) { return name in target ? () => { calls++; throw Error("Must not call native methods during detection"); } : undefined; } });
const desktop = { ...browser, pywebview: { api } };
assert.equal(feature(desktop, "windowsStickers").status, "available");
assert.equal(feature(desktop, "windowsFiles").status, "unavailable", "old/incomplete bridge must not claim absent methods");
assert.equal(feature(desktop, "folderSave").status, "unavailable", "loading state must not imply ability to save it");
const writableDesktop = { ...browser, pywebview: { api: { load_state() {}, save_state() {} } } };
assert.equal(feature(writableDesktop, "folderSave").status, "available");
assert.equal(feature(markerOnly, "folderSave").status, "pending");
assert.equal(feature(desktop, "wordDocuments").status, "limited", "method presence does not prove LibreOffice is installed");
assert.equal(snapshot(desktop, {kind:"python",platform:"win32"}).kind, "python");
assert.equal(feature(desktop, "appUpdates", {kind:"python",platform:"win32"}).status, "unavailable");
assert.equal(feature(desktop, "appUpdates", {kind:"exe",platform:"win32"}).status, "limited");
assert.equal(feature(desktop, "windowsStickers", {kind:"python",platform:"linux"}).status, "unavailable");
assert.equal(feature({ ...desktop, ZETER_TRAINING_RUNTIME: { active: true } }, "windowsStickers").status, "unavailable");
assert.equal(calls, 0);
const folderBrowser = { ...browser, showDirectoryPicker() { throw Error("Do not request permission"); } };
assert.equal(feature(folderBrowser, "folderSave").status, "permission");
assert.equal(feature({ ...folderBrowser, isSecureContext: false }, "folderSave").status, "unavailable");
const notificationBrowser = { ...browser, Notification: Object.assign(function () {}, { permission: "denied" }) };
assert.equal(feature(notificationBrowser, "systemNotifications").status, "unavailable");
notificationBrowser.Notification.permission = "default";
assert.equal(feature(notificationBrowser, "systemNotifications").status, "permission");
notificationBrowser.Notification.permission = "granted";
assert.equal(feature(notificationBrowser, "systemNotifications").status, "limited");
assert.match(owner.featureNoticeHTML("windowsStickers", { windowRef: browser }), /https:\/\/github.com\/zeter1\/ZeTer-OS\/releases/);
assert.doesNotMatch(owner.featureNoticeHTML("windowsStickers", { windowRef: markerOnly }), /Скачать для Windows/, "bridge failure in desktop should not be presented as missing installation");
assert.equal(owner.featureNoticeHTML("windowsStickers", { windowRef: desktop }), "");
assert.match(owner.capabilitiesHTML(snapshot(desktop)), /LibreOffice/);
assert.throws(() => owner.getFeature("typo"), /Unknown/);
console.log("runtime capabilities smoke: PASS (browser/PWA/native/permissions/training; zero native calls)");
