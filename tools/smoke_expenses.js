"use strict";
// Hermetic model/controller regression. VM fixtures only; no app startup or user data.
const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const box = { console, Intl, Date, structuredClone }; box.window = box; vm.createContext(box);
vm.runInContext(fs.readFileSync(path.join(__dirname, "../app/js/core/expenses-utils.js"), "utf8"), box);
const api = box.ZETER_EXPENSES_UTILS, plain = value => JSON.parse(JSON.stringify(value));
async function main() {
  assert.equal(api.parseExpenseAmount("0,10"), 10);
  assert.equal(api.parseExpenseAmount("0.20"), 20);
  assert.equal(api.parseExpenseAmount("1 234,56"), 123456);
  for (const value of ["", "-1", "0", "1.999", "1e3", "Infinity", "1,2.3", "10000000001"]) assert.equal(api.parseExpenseAmount(value), null, value);
  const workspace = { expenses: api.normalizeExpenses(), taskProjects: [{ id: "project1", name: "Проект" }] };
  let refuse = false, held = null, id = 0, stored = null;
  let queue = Promise.resolve();
  const options = { getWorkspace: () => workspace, createId: prefix => `${prefix}_${++id}`,
    persistTransaction: operation => { const run = queue.catch(() => {}).then(() => operation(async candidate => { if (held) await held; if (refuse) throw new Error("Тест: отказ"); stored = plain(candidate); return { saved: true }; })); queue = run; return run; },
    saveSnapshot: (write, candidate) => write(candidate) };
  const controller = api.createExpensesController(options), other = api.createExpensesController(options);
  const category = controller.data().categories[0].id;
  const draft = { amount: "0,10", currency: "BYN", date: "2026-10-31", categoryId: category, title: "Покупка", notes: "", paymentMethod: "Карта", projectId: "project1" };
  const first = await controller.saveEntry(draft);
  await controller.saveEntry({ ...draft, amount: "0.20" });
  assert.equal(api.summarizeExpenses(controller.data(), { month: "2026-10", currency: "BYN" }).netMinor, 30);
  const before = JSON.stringify(workspace);
  refuse = true;
  await assert.rejects(controller.saveEntry({ ...draft, amount: "5" }), /отказ/);
  assert.equal(JSON.stringify(workspace), before);
  refuse = false;
  await controller.saveEntry({ ...draft, amount: "5", currency: "USD", title: "=HYPERLINK(\"evil\")" });
  assert.equal(api.summarizeExpenses(controller.data(), { month: "2026-10", currency: "BYN" }).netMinor, 30);
  assert.equal(api.summarizeExpenses(controller.data(), { month: "2026-10", currency: "USD" }).netMinor, 500);
  const incomeCategory = controller.data().categories.find(item => item.kind === "income").id;
  await controller.saveEntry({ ...draft, kind: "income", amount: "100", categoryId: incomeCategory, title: "Зарплата" });
  const incomeSummary = api.summarizeExpenses(controller.data(), { month: "2026-10", currency: "BYN" });
  assert.equal(incomeSummary.incomeMinor, 10000);
  assert.equal(incomeSummary.balanceMinor, 9970);
  assert.equal(api.filterExpenses(controller.data(), { kind: "income" }).length, 1);
  await assert.rejects(controller.saveEntry({ ...draft, kind: "income" }), /категори/i);
  await assert.rejects(controller.setBudget({ month: "2026-10", currency: "BYN", categoryId: incomeCategory, amount: "5" }), /категори/i);
  assert.ok(api.expensesCSVRows(controller.data(), { currency: "USD" }).flat().some(cell => String(cell).startsWith("'=HYPERLINK")));
  await assert.rejects(controller.saveEntry({ ...draft, date: "2026-02-30" }), /дат/i);
  const original = plain(first);
  const detached = await controller.saveEntry({ ...draft, amount: "1", title: "Без проекта после правки" });
  await controller.saveEntry({ ...draft, amount: "1", title: detached.title, projectId: "" }, detached.id, plain(detached));
  assert.equal(controller.data().entries.find(item => item.id === detached.id).projectName, "");
  await controller.removeEntry(detached.id);
  await other.saveEntry({ ...draft, amount: "0.15" }, first.id, original);
  await assert.rejects(controller.saveEntry({ ...draft, amount: "0.16" }, first.id, original), /другом окне/i);
  await controller.saveEntry({ ...draft, kind: "refund", originalEntryId: first.id, amount: "0.05", date: "2026-11-01" });
  assert.equal(api.summarizeExpenses(controller.data(), { month: "2026-11", currency: "BYN" }).netMinor, -5);
  await assert.rejects(controller.removeEntry(first.id), /возврат/i);
  await assert.rejects(controller.saveEntry({ ...draft, kind: "refund", originalEntryId: first.id, amount: "1" }), /возврат/i);
  await controller.setBudget({ month: "2026-10", currency: "BYN", categoryId: "", amount: "100" });
  assert.equal(controller.data().budgets[0].limitMinor, 10000);
  const budgetDraft = { month: "2026-10", currency: "BYN", categoryId: "", amount: "150" };
  const originalBudget = plain(controller.data().budgets[0]);
  await other.setBudget({ ...budgetDraft, amount: "200" });
  const changedBudget = JSON.stringify(workspace.expenses);
  await assert.rejects(controller.setBudget(budgetDraft, originalBudget), /лимит.*измен/i);
  await assert.rejects(controller.setBudget({ ...budgetDraft, amount: "" }, originalBudget), /лимит.*измен/i);
  assert.equal(JSON.stringify(workspace.expenses), changedBudget, "stale budget save/removal must preserve the newer limit");
  const freshBudget = plain(controller.data().budgets.find(item => item.categoryId === ""));
  await other.setBudget({ ...budgetDraft, categoryId: category, amount: "20" });
  await controller.setBudget(budgetDraft, freshBudget);
  assert.equal(controller.data().budgets.find(item => item.categoryId === "").limitMinor, 15000, "an unrelated budget must not cause a conflict");
  await assert.rejects(controller.setBudget({ ...budgetDraft, categoryId: category, amount: "25" }, null), /лимит.*измен/i);
  await controller.setBudget({ ...budgetDraft, categoryId: category, amount: "" });
  const retryBudget = plain(controller.data().budgets.find(item => item.categoryId === ""));
  refuse = true;
  await assert.rejects(controller.setBudget({ ...budgetDraft, amount: "175" }, retryBudget), /отказ/i);
  assert.equal(controller.data().budgets.find(item => item.categoryId === "").limitMinor, 15000);
  refuse = false;
  await controller.setBudget({ ...budgetDraft, amount: "175" }, retryBudget);
  assert.equal(controller.data().budgets.find(item => item.categoryId === "").limitMinor, 17500);
  await controller.setBudget({ month: "2026-10", currency: "BYN", categoryId: "", amount: "" });
  assert.equal(controller.data().budgets.length, 0);
  await controller.setBudget({ month: "2026-09", currency: "BYN", categoryId: "", amount: "100" });
  await controller.setBudget({ month: "2026-09", currency: "BYN", categoryId: category, amount: "20" });
  await controller.setBudget({ month: "2026-09", currency: "USD", categoryId: "", amount: "99" });
  await controller.setBudget({ month: "2026-10", currency: "BYN", categoryId: "", amount: "150" });
  const budgetPreview = () => controller.data().budgets.filter(item => item.currency === "BYN" && ["2026-09", "2026-10"].includes(item.month));
  const copyDraft = { fromMonth: "2026-09", toMonth: "2026-10", currency: "BYN", replaceExisting: false, expectedBudgets: budgetPreview() };
  const beforeCopy = JSON.stringify(workspace);
  refuse = true;
  await assert.rejects(controller.copyBudgets(copyDraft), /отказ/i);
  assert.equal(JSON.stringify(workspace), beforeCopy);
  refuse = false;
  assert.deepEqual(plain(await controller.copyBudgets(copyDraft)), { copied: 1, skipped: 1 });
  assert.equal(controller.data().budgets.find(item => item.month === "2026-10" && item.categoryId === "").limitMinor, 15000);
  assert.equal(controller.data().budgets.find(item => item.month === "2026-10" && item.categoryId === category).limitMinor, 2000);
  assert.equal(controller.data().budgets.filter(item => item.currency === "USD" && item.month === "2026-10").length, 0);
  assert.deepEqual(plain(await controller.copyBudgets({ ...copyDraft, expectedBudgets: budgetPreview() })), { copied: 0, skipped: 2 });
  await controller.copyBudgets({ ...copyDraft, replaceExisting: true, expectedBudgets: budgetPreview() });
  assert.equal(controller.data().budgets.find(item => item.month === "2026-10" && item.categoryId === "").limitMinor, 10000);
  const staleBudgetPreview = budgetPreview();
  await other.setBudget({ month: "2026-09", currency: "BYN", categoryId: category, amount: "25" });
  const beforeStaleCopy = JSON.stringify(workspace);
  await assert.rejects(controller.copyBudgets({ ...copyDraft, replaceExisting: true, expectedBudgets: staleBudgetPreview }), /изменились/i);
  assert.equal(JSON.stringify(workspace), beforeStaleCopy);
  await assert.rejects(controller.copyBudgets({ ...copyDraft, toMonth: "2026-09", expectedBudgets: budgetPreview() }), /месяц/i);
  let release; held = new Promise(resolve => { release = resolve; });
  const pending = controller.saveEntry({ ...draft, amount: "2" });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(JSON.stringify(workspace.expenses), JSON.stringify(stored));
  release(); held = null; await pending;
  const data = controller.data(), bad = plain(data); bad.entries[0].amountMinor = 0.1;
  assert.throws(() => api.validateExpenses(bad), /сумм/i);
  const duplicate = plain(data); duplicate.entries.push(plain(duplicate.entries[0]));
  assert.throws(() => api.validateExpenses(duplicate), /ID/i);
  assert.equal(api.filterExpenses(data, { query: "пОкУпКа", currency: "BYN", from: "2026-10-31", to: "2026-10-31" }).length, 3);
  const copy = api.normalizeExpenses(data); copy.entries[0].title = "changed";
  assert.notEqual(copy.entries[0].title, data.entries[0].title);
  const activeCategory = plain(controller.data().categories.find(item => item.id === category));
  await controller.saveCategory({ ...activeCategory, archived: true }, category, activeCategory);
  const beforeHiddenCategory = JSON.stringify(workspace.expenses);
  await assert.rejects(controller.saveEntry({ ...draft, amount: "1" }), /категория.*скрыта|категория.*недоступна/i);
  assert.equal(JSON.stringify(workspace.expenses), beforeHiddenCategory);
  await controller.saveCategory(activeCategory, category);
  const historicalEntry = controller.data().entries.find(item => item.id === first.id);
  workspace.taskProjects = [];
  await controller.saveEntry({ ...draft, amount: "0.15", title: "Исторический проект" }, first.id, plain(historicalEntry));
  assert.equal(controller.data().entries.find(item => item.id === first.id).projectName, "Проект");
  console.log("expenses model smoke: ok (exact money, currencies, dates, refund links, filtered CSV, budgets, ACK/failure/retry, stale edits, isolation)");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
