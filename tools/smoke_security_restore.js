async function verifyAutomationRestore() {
  const core = path.dirname(modulePath);
  vm.runInContext(fs.readFileSync(path.join(core, "automation-utils.js"), "utf8"), box, { filename: "automation-utils.js" });
  const automation = box.window.ZETER_AUTOMATION_UTILS;
  const source = fixture(), live = fixture();
  const rule = { id: "rule", name: "Workflow", enabled: true, type: "note_created", noteFolderId: "folder", conditions: [], actions: [{ id: "create_action", type: "create_note", name: "Result", content: "folder", parentId: "folder" }] };
  source.desktops[0].data.automations = [rule];
  live.desktops[1].data.automations = [{ id: "unrelated_rule", enabled: true, type: "startup", actions: [{ type: "notify" }] }];
  const copy = plan(live, source, choose("desktop", "desktop"));
  const restored = copy.state.desktops.at(-1).data, restoredRule = restored.automations[0];
  const restoredFolder = Object.values(copy.state.fs).find(item => item.id !== "folder" && item.parent === copy.state.desktops.at(-1).id && item.type === "folder");
  const restoredNote = Object.values(copy.state.fs).find(item => item.type === "note" && item.parent === restoredFolder.id);
  const context = { now: 100, triggerType: "note_created", triggerId: restoredNote.id, note: restoredNote, state: copy.state, workspace: restored };
  assert.ok(automation.pendingRunForAutomation({ ...restoredRule, enabled: true }, context), "after explicit enable, real trigger owner must recognize the restored note's folder");
  let callbackParent;
  await automation.executeAutomationAction({ ...restoredRule, enabled: true }, {}, { context, createNote: draft => { callbackParent = draft.parentId; return { kind: "fs", id: "created_by_test" }; } });
  assert.equal(callbackParent, restoredFolder.id, "real create_note callback must receive restored folder ID");
  assert.equal(restoredRule.enabled, false, "recovered rule cannot execute automatically before user enables it");
  assert.equal(automation.pendingRunForAutomation(restoredRule, context), null);
  assert.ok(copy.warnings.includes("Восстановленные автоматизации выключены. Проверь правила и включи их вручную."));
  assert.equal(copy.state.desktops[1].data.automations[0].enabled, true);
  const replace = plan(live, source, choose("desktop", "desktop"), "replace");
  assert.equal(replace.state.desktops[0].data.automations[0].enabled, false);
  assert.equal(replace.state.desktops[1].data.automations[0].enabled, true);
  const typed = fixture();
  typed.desktops[0].data.automations = [plain(automation.normalizeAutomation({ ...rule, conditions: [
    { type: "file_source_folder", value: "folder" }, { type: "task_project", value: "p" },
    { type: "object_exists", mode: "selected", kind: "fs", value: "note" },
    { type: "object_exists", mode: "selected", kind: "event", value: "e" },
    { type: "object_exists", mode: "selected", kind: "task", value: "t" },
    { type: "note_content_contains", value: "folder" }, { type: "file_name_contains", value: "p" }
  ], actions: [rule.actions[0], { type: "link_objects", left: { mode: "selected", kind: "fs", id: "note" }, right: { mode: "selected", kind: "event", id: "e" } }, { type: "move_file", targetFolderId: "folder" }] }))];
  typed.fs.shortcut = { id: "shortcut", type: "shortcut", parent: "folder", name: "Open note", shortcut: { kind: "zeter", target: "zeter://item/note", itemId: "note" }, managedFile: { id: "shortcut_ref", kind: "shortcut", shortcutTarget: "zeter://item/note", shortcutKind: "zeter" } };
  const typedCopy = plan(live, typed, choose("desktop", "desktop"));
  const typedData = typedCopy.state.desktops.at(-1).data, typedRule = typedData.automations[0];
  const copiedTask = typedData.tasks[0], copiedProject = typedData.taskProjects[0], typedNote = typedCopy.state.fs[copiedProject.attachments[0].id];
  const conditions = typedRule.conditions;
  assert.deepEqual(plain(conditions.slice(0, 5).map(condition => condition.value)), [typedNote.parent, copiedProject.id, typedNote.id, typedData.events[0].id, copiedTask.id]);
  assert.deepEqual(plain(conditions.slice(5).map(condition => condition.value)), ["folder", "p"], "text comparison values remain literal user content");
  assert.equal(typedRule.actions[0].content, "folder");
  assert.equal(typedRule.action.id, typedRule.actions[0].id, "canonical action alias remains valid");
  assert.equal(typedRule.actions[1].left.id, typedNote.id);
  assert.equal(typedRule.actions[1].right.id, typedData.events[0].id);
  assert.equal(typedRule.actions[2].targetFolderId, typedNote.parent);
  assert.equal(automation.evaluateAutomationConditions({ ...typedRule, conditions: conditions.slice(0, 5) }, { state: typedCopy.state, workspace: typedData, file: { parent: typedNote.parent }, task: copiedTask }).passed, true);
  const shortcut = Object.values(typedCopy.state.fs).find(item => item.type === "shortcut" && item.id !== "shortcut");
  assert.equal(shortcut.shortcut.target, `zeter://item/${typedNote.id}`);
  assert.equal(shortcut.managedFile.shortcutTarget, shortcut.shortcut.target);
  assert.equal(shortcut.shortcut.itemId, typedNote.id);
}
