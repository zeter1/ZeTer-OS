"use strict";
// Normalizer/patch fixture; never starts the app or opens real data.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const sandbox = { window: { ZETER_CORE_UTILS: { clamp: (n, a, b) => Math.max(a, Math.min(b, n)), uid: () => 'fixture', escapeHtml: String }, ZETER_ASSET_UTILS: {}, ZETER_OS_CONFIG: {} } };
for (const file of ['system-settings-utils', 'visual-utils', 'settings-ui-utils']) vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../app/js/core', file + '.js'), 'utf8'), sandbox);
const sys = sandbox.window.ZETER_SYSTEM_SETTINGS_UTILS, visual = sandbox.window.ZETER_VISUAL_UTILS;
const plain = value => JSON.parse(JSON.stringify(value));
const defaults = sys.normalizeSystemSettings();
assert.equal(defaults.windows.placement, 'center');
assert.equal(defaults.clock.format, '24h');
assert.equal(defaults.clock.showSeconds, false);
assert.equal(defaults.clock.showDate, true);
assert.equal(defaults.calendar.weekStart, 'monday');
assert.equal(defaults.notifications.popupDuration, 3500);
for (const scale of [90, 100, 110, 120, 130, 140, 150]) assert.equal(sys.normalizeSystemSettings({accessibility:{textScale:scale}}).accessibility.textScale, scale);
const normalized = sys.normalizeSystemSettings({ unknown: 8, clock: {format:'12h',showDate:false,unknown:5}, windows: {placement:'last',lastPositions:{notes:{left:20,top:30,width:700,height:500},bad:{left:NaN}}}, notifications:{popupDuration:'8000'}, calendar:{weekStart:'sunday'} });
assert.equal(normalized.clock.unknown, 5);
assert.equal(normalized.unknown, 8);
assert.equal(normalized.clock.format, '12h');
assert.equal(normalized.windows.lastPositions.notes.left, 20);
assert.equal(normalized.windows.lastPositions.bad, undefined);
assert.equal(normalized.notifications.popupDuration, 8000);
assert.equal(normalized.calendar.weekStart, 'sunday');
assert.equal(sys.normalizeSystemSettings({clock:{format:'junk'},windows:{placement:'junk'},calendar:{weekStart:'junk'}}).clock.format, '24h');
assert.deepEqual(plain(visual.normalizeDesktopAppearance()), {iconSize:'medium',density:'compact',extensions:true,labelSize:'medium',labelLines:0,openMode:'double'});
assert.equal(visual.normalizeDesktopAppearance({labelLines:'3',labelSize:'large',openMode:'single',unknown:9}).labelLines,3);
assert.equal(visual.normalizeDesktopAppearance({labelLines:7,labelSize:'junk'}).labelLines,0);
assert.equal(visual.normalizeDesktopAppearance({unknown:9}).unknown,9);
assert.equal(visual.normalizeVisualSettings({accent:'junk'}).accent, 'blue');
assert.equal(visual.ACCENT_PRESETS.length,5);
const ui=sandbox.window.ZETER_SETTINGS_UI_UTILS;
const sentinel={settings:{...visual.baseDesktopSettings(),customWallpaper:{dataURL:'data:image/png;base64,AA==',name:'keep'},unknown:9},systemSettings:sys.normalizeSystemSettings({windows:{lastPositions:{notes:{left:20,top:30,width:700,height:500}}},unknown:8}),desktop:{name:'Мой стол',description:'Описание',icon:{name:'keep'},data:{tasks:[{id:'keep'}]}}};
const preferences=ui.settingsPreferences(sentinel);
assert.equal(preferences['desktop.desktopAppearance.labelLines'],0);
const patched=ui.applySettingsPreferencePatch(sentinel,{'desktop.accent':'violet','system.clock.format':'12h','desktop.desktopAppearance.labelLines':2,'profile.name':'Другой','system.__proto__.polluted':true});
assert.equal(patched.settings.accent,'violet');assert.equal(patched.systemSettings.clock.format,'12h');assert.equal(patched.desktop.name,'Другой');
assert.equal(sentinel.desktop.name,'Мой стол');assert.equal({}.polluted,undefined);
const reset=ui.applySettingsPreferencePatch(patched,ui.settingsResetPatch('appearance'));
assert.equal(reset.settings.accent,'blue');assert.equal(reset.desktop.name,'Другой');
assert.deepEqual(plain(reset.settings.customWallpaper),plain(sentinel.settings.customWallpaper));
assert.deepEqual(plain(reset.desktop.data),plain(sentinel.desktop.data));assert.equal(reset.settings.unknown,9);
assert.deepEqual(plain(reset.systemSettings.windows.lastPositions),plain(sentinel.systemSettings.windows.lastPositions));
assert.equal(Object.keys(ui.settingsResetPatch('storage')).length,0);
console.log('settings preferences: PASS (defaults, compatibility, invalid/unknown fields, geometry, desktop, 150%)');
