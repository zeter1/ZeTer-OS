const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const root = process.argv[2] || path.resolve(__dirname, "..");
const box = { console, structuredClone }; box.window = box; vm.createContext(box);
vm.runInContext(fs.readFileSync(path.join(root, "app/js/core/shopping-utils.js"), "utf8"), box);
const plain = x => JSON.parse(JSON.stringify(x));
async function main() {
  const api = box.ZETER_SHOPPING_UTILS;
  const workspace = {}, neighbor = { sentinel: "Соседний стол" };
  let counter = 0, refuse = false, durable, queue = Promise.resolve();
  const options = { getWorkspace: () => workspace, createId: prefix => `${prefix}_${++counter}`,
    persistTransaction: run => { const next = queue.catch(() => {}).then(() => run(async snapshot => { if (refuse) throw new Error("test: отказ записи"); durable = plain(snapshot); return { saved: true }; })); queue = next; return next; },
    saveSnapshot: (write, shopping) => write({ shopping, neighbor }) };
  const controller = api.createShoppingController(options), otherWindow = api.createShoppingController(options);
  const preferences = { density: "normal", groupByCategory: true, showDescriptions: true };
  assert.deepEqual(plain(controller.data()), { projects: [], categories: [], items: [], preferences });
  assert.deepEqual(plain(api.normalizeShopping({ projects: [], categories: [], items: [] }).preferences), preferences);
  refuse = true;
  await assert.rejects(controller.setPreferences({ ...preferences, density: "compact" }, preferences), /отказ/);
  assert.deepEqual(plain(controller.data().preferences), preferences);
  refuse = false;
  await controller.setPreferences({ ...preferences, density: "compact" }, preferences);
  const currentPreferences = plain(controller.data().preferences);
  await assert.rejects(otherWindow.setPreferences({ ...preferences, showDescriptions: false }, preferences), /измен/i);
  assert.deepEqual(plain(controller.data().preferences), currentPreferences);
  await assert.rejects(controller.setPreferences({ ...preferences, density: "invalid" }, currentPreferences), /настрой/i);
  await assert.rejects(controller.setPreferences({ ...preferences, showDescriptions: "false" }, currentPreferences), /настрой/i);
  await controller.setPreferences(preferences, currentPreferences);
  const list = await controller.saveProject({ name: "Продукты" });
  const second = await controller.saveProject({ name: "Для дома" });
  const category = await controller.saveCategory({ projectId: list.id, name: "Молочное" });
  const foreign = await controller.saveCategory({ projectId: second.id, name: "Молочное" });
  await assert.rejects(controller.saveCategory({ projectId: list.id, name: "молочное" }), /уникаль/i);
  await assert.rejects(controller.saveItem({ projectId: list.id, categoryId: foreign.id, name: "Чужая категория" }), /категор/i);
  const item = await controller.saveItem({ projectId: list.id, categoryId: category.id, name: '<img src=x onerror="bad()">', quantity: "2 пачки", notes: "Без сахара" });
  assert.equal(item.bought, false);
  refuse = true;
  await assert.rejects(controller.setBought(item.id, true), /отказ/);
  assert.equal(controller.data().items[0].bought, false);
  refuse = false; await controller.setBought(item.id, true);
  assert.equal(durable.shopping.items[0].bought, true);
  await assert.rejects(controller.saveItem({ ...plain(item), name: "Устаревший ввод" }, item.id, item), /измен/i);
  await Promise.all([controller.saveItem({ projectId: list.id, name: "Молоко", quantity: "1 л" }), otherWindow.saveItem({ projectId: second.id, name: "Мыло" })]);
  assert.equal(controller.data().items.length, 3);
  await assert.rejects(controller.saveProject({ name: " продукты " }), /существ|уникаль/i);
  await assert.rejects(controller.saveItem({ projectId: "missing", name: "Потерянная связь" }), /проект/i);
  const malformed = plain(controller.data()); malformed.items[0].bought = "false";
  assert.throws(() => api.validateShopping(malformed), /покуп|отмет/i);
  const links = plain(controller.data()); links.items[0].projectId = "missing";
  assert.throws(() => api.validateShopping(links), /проект/i);
  const snapshot = controller.data().items.filter(x => x.projectId === list.id && x.bought);
  await controller.clearBought(list.id, snapshot);
  assert.equal(controller.data().items.length, 2);
  const retained = await controller.saveItem({ projectId: list.id, categoryId: category.id, name: "Сыр" });
  refuse = true;
  await assert.rejects(controller.removeCategory(category.id, category), /отказ/);
  assert.equal(controller.data().items.find(row => row.id === retained.id).categoryId, category.id);
  refuse = false;
  await controller.removeCategory(category.id, category);
  assert.equal(controller.data().items.find(row => row.id === retained.id).name, "Сыр");
  assert.ok(controller.data().items.every(row => row.categoryId !== category.id));
  const original = controller.data().projects.find(x => x.id === list.id);
  const rows = controller.data().items.filter(x => x.projectId === list.id);
  refuse = true;
  await assert.rejects(controller.removeProject(list.id, original, rows, []), /отказ/);
  assert.equal(controller.data().projects.length, 2);
  refuse = false; await controller.removeProject(list.id, original, rows, []);
  assert.equal(controller.data().items[0].projectId, second.id);
  assert.equal(neighbor.sentinel, "Соседний стол");
  assert.deepEqual(plain(controller.data()), durable.shopping);
  api.validateShopping(controller.data());
  const unconfirmed = api.createShoppingController({ ...options, saveSnapshot: async () => ({ saved: false }) });
  await assert.rejects(unconfirmed.saveProject({ name: "Не записано" }), /подтверд/i);
  assert.equal(controller.data().projects.length, 1);
  console.log("shopping smoke: PASS (validation, staged ACK, failure/retry, stale edit, serial windows, clear/delete, neighbor preservation)");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
