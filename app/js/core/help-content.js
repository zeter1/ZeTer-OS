  function helpClickAction(target) {
    const appButton = target?.closest?.("[data-help-app]");
    if (appButton) return { type: "open-app", appId: appButton.dataset.helpApp || "" };
    if (target?.closest?.("[data-help-clear]")) return { type: "search", query: "" };
    const queryButton = target?.closest?.("[data-help-query]");
    if (queryButton) return { type: "search", query: queryButton.dataset.helpQuery || "" };
    const targetButton = target?.closest?.("[data-help-target]");
    if (targetButton) return { type: "navigate", targetId: targetButton.dataset.helpTarget || "start" };
    return null;
  }

  function applyHelpSearch(root, value = "") {
    if (!root?.querySelectorAll) return { query: normalizeHelpQuery(value), sections: 0, topics: 0 };
    const query = normalizeHelpQuery(value);
    let visibleSections = 0;
    let visibleTopics = 0;

    root.querySelectorAll("[data-help-section]").forEach(section => {
      const sectionMatches = helpTextMatches(section.dataset.helpKeywords || "", query);
      let sectionTopicCount = 0;
      section.querySelectorAll("[data-help-searchable]").forEach(topic => {
        const matches = sectionMatches || helpTextMatches(topic.textContent || "", query);
        topic.hidden = !matches;
        if (matches) {
          sectionTopicCount++;
          visibleTopics++;
        }
        if (query && matches && !topic.open) {
          topic.open = true;
          topic.dataset.helpOpenedBySearch = "1";
        }
        if (!query && topic.dataset.helpOpenedBySearch === "1") {
          topic.open = false;
          delete topic.dataset.helpOpenedBySearch;
        }
      });
      section.hidden = query ? !sectionTopicCount : section.id !== `help-${root.dataset?.helpCurrentSection || "home"}`;
      if (!section.hidden) visibleSections++;
    });

    const empty = root.querySelector("[data-help-empty]");
    if (empty) empty.hidden = !query || visibleTopics > 0;
    const status = root.querySelector("[data-help-search-status]");
    if (status) {
      const totalTopics = HELP_SECTIONS.reduce((count, section) => count + section.topics.length, 0);
      status.textContent = query
        ? (visibleTopics ? `Найдено тем: ${visibleTopics}` : "Совпадений нет")
        : `${HELP_SECTIONS.length} разделов · ${totalTopics} тем`;
    }
    const home = root.querySelector("[data-help-home]");
    if (home) home.hidden = Boolean(query) || Boolean(root.dataset?.helpCurrentSection && root.dataset.helpCurrentSection !== "home");
    const results = root.querySelector("[data-help-results]");
    if (results) results.hidden = !query;
    root.querySelectorAll(".help-nav [data-help-target]").forEach(button => {
      if (!query && button.dataset.helpTarget === (root.dataset?.helpCurrentSection || "home")) button.setAttribute("aria-current", "page");
      else button.removeAttribute("aria-current");
    });
    const clear = root.querySelector(".help-search-panel [data-help-clear]");
    if (clear) clear.hidden = !query;
    root.classList?.toggle?.("help-search-active", Boolean(query));
    return { query, sections: visibleSections, topics: visibleTopics };
  }

  function bindHelpInteractions(root, options = {}) {
    if (!root?.addEventListener) return root;
    const openApp = typeof options.openApp === "function" ? options.openApp : () => {};
    const search = root.querySelector("[data-help-search]");

    root.addEventListener("click", event => {
      const action = helpClickAction(event.target);
      if (!action) return;
      if (action.type === "open-app" && action.appId) {
        openApp(action.appId);
        return;
      }
      if (action.type === "search") {
        if (search) search.value = action.query;
        applyHelpSearch(root, action.query);
        search?.focus?.();
        root.scrollTop = 0;
        return;
      }
      if (action.targetId !== "top") {
        root.dataset.helpCurrentSection = action.targetId;
        if (search) search.value = "";
        applyHelpSearch(root, "");
      }
      const selector = action.targetId === "top" || action.targetId === "home" ? "#help-top" : `#help-${action.targetId}`;
      const destination = root.querySelector(selector);
      root.scrollTop = 0;
      if (action.targetId !== "top" && action.targetId !== "home") destination?.focus?.({ preventScroll: true });
    });

    search?.addEventListener("input", event => applyHelpSearch(root, event.target.value));
    search?.addEventListener("keydown", event => {
      if (event.key !== "Escape" || !search.value) return;
      event.preventDefault();
      search.value = "";
      applyHelpSearch(root, "");
    });
    applyHelpSearch(root, search?.value || "");
    return root;
  }

  function helpAppElement(options = {}) {
    const documentRef = options.documentRef || document;
    const root = documentRef.createElement("div");
    root.className = "browser-page help-page";
    root.innerHTML = helpContentHTML({ osVersion: options.osVersion || "" });
    return bindHelpInteractions(root, options);
  }

