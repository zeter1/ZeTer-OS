  function normalizeHelpQuery(value = "") {
    return String(value || "").trim().toLocaleLowerCase("ru-RU");
  }

  function helpTextMatches(text = "", query = "") {
    const normalizedQuery = normalizeHelpQuery(query);
    return !normalizedQuery || normalizeHelpQuery(text).includes(normalizedQuery);
  }

  function helpStepsHTML(steps = []) {
    if (!Array.isArray(steps) || !steps.length) return "";
    return `<ol class="help-steps">${steps.map(step => `<li>${escapeHtml(step)}</li>`).join("")}</ol>`;
  }

  function helpTopicHTML(topic = {}, options = {}) {
    const open = options.open ? " open" : "";
    const tip = topic.tip ? `<p class="help-callout tip"><b>Полезно:</b> ${escapeHtml(topic.tip)}</p>` : "";
    const warning = topic.warning ? `<p class="help-callout warning"><b>Важно:</b> ${escapeHtml(topic.warning)}</p>` : "";
    const action = topic.appId
      ? `<button type="button" class="help-topic-action" data-help-app="${safeAttr(topic.appId)}">${escapeHtml(topic.actionLabel || "Открыть приложение")}</button>`
      : "";
    return `
      <details class="help-topic" data-help-searchable${open}>
        <summary>
          <span class="help-topic-icon" aria-hidden="true">${escapeHtml(topic.icon || "•")}</span>
          <span class="help-topic-title"><b>${escapeHtml(topic.title || "Тема")}</b><small>${escapeHtml(topic.summary || "")}</small></span>
        </summary>
        <div class="help-topic-body">
          ${helpStepsHTML(topic.steps)}
          ${tip}${warning}${action}
        </div>
      </details>`;
  }

  function helpSectionHTML(section = {}) {
    const keywords = [section.title, section.summary, section.keywords].filter(Boolean).join(" ");
    return `
      <section class="help-section" id="help-${safeAttr(section.id)}" data-help-section data-help-keywords="${safeAttr(keywords)}" tabindex="-1">
        <div class="help-section-head">
          <span aria-hidden="true">${escapeHtml(section.icon || "•")}</span>
          <div><p>Раздел</p><h2>${escapeHtml(section.title || "Справка")}</h2><small>${escapeHtml(section.summary || "")}</small></div>
        </div>
        <div class="help-topic-list">${(section.topics || []).map((topic, index) => helpTopicHTML(topic, { open: section.id === "start" && index === 0 })).join("")}</div>
      </section>`;
  }

